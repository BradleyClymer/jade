const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('jade', {
  readFile: (filePath) => ipcRenderer.invoke('read-file', filePath),
  writeFile: (filePath, content) => ipcRenderer.invoke('write-file', filePath, content),
  saveDialog: () => ipcRenderer.invoke('save-dialog'),
  confirmDiscard: (fileName) => ipcRenderer.invoke('confirm-discard', fileName),
  getTitle: (filePath, modified) => ipcRenderer.invoke('get-title', filePath, modified),
  setTitle: (title) => ipcRenderer.send('set-title', title),
  exportPdf: (html, pageSize) => ipcRenderer.invoke('export-pdf', html, pageSize),
  saveImage: (dir, filename, base64) => ipcRenderer.invoke('save-image', dir, filename, base64),
  exportLatex: () => ipcRenderer.invoke('export-latex'),
  updateRecentFiles: (files) => ipcRenderer.send('update-recent-files', files),
  selectDirectory: () => ipcRenderer.invoke('select-directory'),
  openCSSFile: () => ipcRenderer.invoke('open-css-file'),

  onOpenFile: (cb) => ipcRenderer.on('open-file', (_, path) => cb(path)),
  onNewFile: (cb) => ipcRenderer.on('new-file', () => cb()),
  onSaveFile: (cb) => ipcRenderer.on('save-file', () => cb()),
  onSaveFileAs: (cb) => ipcRenderer.on('save-file-as', () => cb()),
  onCloseTab: (cb) => ipcRenderer.on('close-tab', () => cb()),
  onTogglePreview: (cb) => ipcRenderer.on('toggle-preview', () => cb()),
  onSetView: (cb) => ipcRenderer.on('set-view', (_, mode) => cb(mode)),
  onZoom: (cb) => ipcRenderer.on('zoom', (_, dir) => cb(dir)),
  onFind: (cb) => ipcRenderer.on('find', () => cb()),
  onReplace: (cb) => ipcRenderer.on('replace', () => cb()),
  onExportPdf: (cb) => ipcRenderer.on('export-pdf', () => cb()),
  onExportLatex: (cb) => ipcRenderer.on('export-latex', () => cb()),
  onOpenRecent: (cb) => ipcRenderer.on('open-recent', (_, path) => cb(path)),
  onSetTheme: (cb) => ipcRenderer.on('set-theme', (_, theme) => cb(theme)),
  onExportLatexProject: (cb) => ipcRenderer.on('export-latex-project', () => cb()),
  onSelectCustomCSS: (cb) => ipcRenderer.on('select-custom-css', () => cb()),
  onClearCustomCSS: (cb) => ipcRenderer.on('clear-custom-css', () => cb()),
  onToggleOutline: (cb) => ipcRenderer.on('toggle-outline', () => cb()),
  onSetPdfPageSize: (cb) => ipcRenderer.on('set-pdf-page-size', (_, size) => cb(size)),
  onToggleMinimap: (cb) => ipcRenderer.on('toggle-minimap', () => cb()),
  onOpenSnippets: (cb) => ipcRenderer.on('open-snippets', () => cb()),
  onOpenTableEditor: (cb) => ipcRenderer.on('open-table-editor', () => cb()),
  loadPlugins: () => ipcRenderer.invoke('load-plugins'),
  openPluginDir: () => ipcRenderer.invoke('open-plugin-dir'),
  onReloadPlugins: (cb) => ipcRenderer.on('reload-plugins', () => cb()),
  onOpenPluginDir: (cb) => ipcRenderer.on('open-plugin-dir', () => cb()),
  onMoveTabToWindow: (cb) => ipcRenderer.on('move-tab-to-window', () => cb()),
  openInNewWindow: (filePath) => ipcRenderer.invoke('open-in-new-window', filePath),
  onToggleGitPanel: (cb) => ipcRenderer.on('toggle-git-panel', () => cb()),
  onShowGitDiff: (cb) => ipcRenderer.on('show-git-diff', () => cb()),
  gitStatus: (cwd) => ipcRenderer.invoke('git-status', cwd),
  gitDiff: (cwd, filePath) => ipcRenderer.invoke('git-diff', cwd, filePath),
  gitStage: (cwd, filePath) => ipcRenderer.invoke('git-stage', cwd, filePath),
  gitUnstage: (cwd, filePath) => ipcRenderer.invoke('git-unstage', cwd, filePath),
  gitCommit: (cwd, message) => ipcRenderer.invoke('git-commit', cwd, message),
  gitLog: (cwd, count) => ipcRenderer.invoke('git-log', cwd, count),
});
